#!/usr/bin/env python3
# tier0.py - generate the Tier 0 header checks from the spec model.
#
# Copyright (c) 2026 Nicholas Martin. All rights reserved.
#
# Tier 0 asks only whether each header provides what the standard lists:
# every macro defined, every type and structure member present (members
# with their types), every function declared with its prototype, every
# external variable declared. One test per item, so one missing name
# does not hide the rest; a test that does not compile is the FAIL
# (MODULE "buildfail FAIL").
#
# The tests are derived from the standard, so like the model they live
# under build/ and are never committed or bundled (RULES.md, rule 3).
# Build them on a machine with the standard, then copy build/tier0 with
# the suite to the system under test.
#
# usage: gen/tier0.py [--model build/spec/model.json] [--out build/tier0]
#        then: sh posixcheck.sh --root build/tier0/modules --results results-t0

import argparse
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PRE = """/*
 * Tier 0: {what}
 * Generated by gen/tier0.py from the user's copy of the standard; not
 * part of the repository.
 *
 * ASSERTION {aid}
 */
#include <{hdr}>

/* The harness, declared here so that no other header is included. */
void pc_begin(const char *);
void pc_test(void);
_Noreturn void pc_pass(void);
_Noreturn void pc_fail(const char *, ...);
_Noreturn void pc_unresolved(const char *, ...);

#define IS_T(e, T) _Generic((e), T: 1, default: 0)
"""


def slug(hdr):
    return hdr.replace("/", "_")


def ptr_to(ty):
    """The type 'pointer to ty' as a C type name."""
    if "(*)" in ty:
        return ty.replace("(*)", "(**)", 1)
    if "(*" in ty:
        return None
    return ty + " *"


def paren_span(s, open_at):
    depth = 0
    for i in range(open_at, len(s)):
        if s[i] == "(":
            depth += 1
        elif s[i] == ")":
            depth -= 1
            if depth == 0:
                return i
    return None


def fn_types(decl, name):
    """(pointer type, pointer type with one more int parameter or None)."""
    # a function specifier is not part of the type
    decl = re.sub(r"\b(_Noreturn|noreturn|inline)\s+", "", decl)
    m = re.search(r"\b" + re.escape(name) + r"\s*\(", decl)
    if not m:
        return None, None
    op = decl.index("(", m.start())
    cl = paren_span(decl, op)
    if cl is None:
        return None, None
    params = decl[op + 1:cl].strip()
    ptr = decl[:m.start()] + "(*)" + decl[op:]
    if "..." in params:
        extra = None
    else:
        newp = "int" if params in ("void", "") else params + ", int"
        extra = decl[:m.start()] + "(*)(" + newp + ")" + decl[cl + 1:]
    return ptr.strip(), extra.strip() if extra else None


def c_str(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


# Names that C23 makes keywords; POSIX.1-2024 builds on C17, where they
# are macros. Under a later C the check cannot be made.
C23_KEYWORDS = {"bool", "true", "false", "alignas", "alignof", "thread_local", "static_assert"}
# Names the standard allows to be a macro or an identifier.
MACRO_OR_IDENT = {"math_errhandling"}


def body_usable(aid, name, why):
    return f"""
int main(void)
{{
	pc_begin("{aid}");
	pc_test();
	(void)({name});	/* {why} */
	pc_pass();
}}
"""


def body_macro(aid, hdr, name, always=None):
    if name in C23_KEYWORDS:
        return f"""
int main(void)
{{
	pc_begin("{aid}");
#if __STDC_VERSION__ > 201710L
	pc_unresolved("compiled as C later than C17, where {name} is a keyword; use a c17 compiler");
#else
	pc_test();
#ifndef {name}
	pc_fail("<{hdr}> does not define {name}");
#else
	pc_pass();
#endif
#endif
}}
"""
    if name in MACRO_OR_IDENT:
        return body_usable(aid, name, "a macro or an identifier")
    val = ""
    if always == "!= -1":
        val = f"""#elif {name} == -1
	pc_fail("{name} is -1");
"""
    elif always and re.match(r"^[0-9]+L?$", always):
        val = f"""#elif {name} != {always}
	pc_fail("{name} is not {always}");
"""
    elif always == "> 0":
        val = f"""#elif {name} <= 0
	pc_fail("{name} is not greater than zero");
"""
    return f"""
int main(void)
{{
	pc_begin("{aid}");
	pc_test();
#ifndef {name}
	pc_fail("<{hdr}> does not define {name}");
{val}#else
	pc_pass();
#endif
}}
"""


def body_type(aid, name):
	return f"""
static {name} *pc_t0_p;

int main(void)
{{
	pc_begin("{aid}");
	pc_test();
	(void)pc_t0_p;
	pc_pass();
}}
"""


def body_complete(aid, name):
    return f"""
typedef char pc_t0_c[sizeof({name})];	/* a complete type */

int main(void)
{{
	pc_begin("{aid}");
	pc_test();
	pc_pass();
}}
"""


def body_member(aid, agg, mem):
    lines = [f"\nstatic {agg} pc_t0_s;\n", "int main(void)\n{", f'\tpc_begin("{aid}");', "\tpc_test();"]
    if mem["array"]:
        pt = ptr_to(mem["type"])
        lines.append(f"\t(void)sizeof pc_t0_s.{mem['name']};")
        if pt:
            lines.append(f'\tif (!IS_T(&pc_t0_s.{mem["name"]}[0], {pt}))')
            lines.append(f'\t\tpc_fail("{agg} member {mem["name"]} is not an array of {c_str(mem["type"])}");')
            if "(*" not in mem["type"]:
                n = f"sizeof pc_t0_s.{mem['name']} / sizeof pc_t0_s.{mem['name']}[0]"
                lines.append(f'\tif (!IS_T(&pc_t0_s.{mem["name"]}, {mem["type"]} (*)[{n}]))')
                lines.append(f'\t\tpc_fail("{agg} member {mem["name"]} is not an array");')
    else:
        pt = ptr_to(mem["type"])
        lines.append(f"\t(void)sizeof pc_t0_s.{mem['name']};")
        if pt:
            lines.append(f'\tif (!IS_T(&pc_t0_s.{mem["name"]}, {pt}))')
            lines.append(f'\t\tpc_fail("{agg} member {mem["name"]} is not of type {c_str(mem["type"])}");')
    lines += ["\tpc_pass();", "}", ""]
    return "\n".join(lines)


def body_function(aid, f):
    name = f["name"]
    if f.get("decl") and re.search(r"real-floating|\bgeneric\b", f["decl"]):
        # a type-generic macro: it must be defined as a macro
        return body_macro(aid, f.get("_hdr", ""), name)
    if f.get("either") or not f.get("decl"):
        return f"""
int main(void)
{{
	pc_begin("{aid}");
	pc_test();
#ifndef {name}
	(void)&({name});	/* declared as a function, if not defined as a macro */
#endif
	pc_pass();
}}
"""
    ptr, extra = fn_types(f["decl"], name)
    if ptr is None:
        return None
    s = f"""
int main(void)
{{
	pc_begin("{aid}");
	pc_test();
	if (!IS_T(&({name}), {ptr}))
		pc_fail("{name}() is not declared as {c_str(f['decl'])}");
"""
    if extra:
        s += f"""	if (IS_T(&({name}), {extra}))
		pc_fail("{name}() is declared without a prototype");
"""
    s += "\tpc_pass();\n}\n"
    return s


def body_variable(aid, v):
    name = v["name"]
    s = f"""
int main(void)
{{
	pc_begin("{aid}");
	pc_test();
	(void)&({name});
"""
    ty = v.get("type", "")
    if ty and "[" not in ty:
        s += f"""	if (!IS_T(&({name}), {ty} *))
		pc_fail("{name} is not declared as {c_str(ty)}");
"""
    s += "\tpc_pass();\n}\n"
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=str(ROOT / "build/spec/model.json"))
    ap.add_argument("--out", default=str(ROOT / "build/tier0"))
    ap.add_argument("--header", action="append", help="only these headers")
    a = ap.parse_args()
    models = json.loads(Path(a.model).read_text())
    out = Path(a.out) / "modules" / "xbd"
    if out.exists():
        shutil.rmtree(out)
    total = skipped = 0
    for m in models:
        hdr = m["header"]
        if a.header and hdr not in a.header:
            continue
        items = []   # (kind, name, what, option, body)
        for x in m["macros"]:
            if x.get("conditional"):
                skipped += 1
                continue
            if x.get("enum"):
                items.append(("enum", x["name"], f"<{hdr}> defines the enumeration constant {x['name']}", x["option"],
                              lambda aid, x=x: body_usable(aid, x["name"], "an enumeration constant (or a macro)")))
                continue
            items.append(("mac", x["name"], f"<{hdr}> defines {x['name']}" + ("()" if x.get("function_like") else "")
                          + (f" as {x['always']}" if x.get("always") not in (None, "defined") else ""),
                          x["option"], lambda aid, x=x, hdr=hdr: body_macro(aid, hdr, x["name"], x.get("always"))))
        for x in m["types"]:
            items.append(("type", x["name"], f"<{hdr}> defines the type {x['name']}", x["option"],
                          lambda aid, x=x: body_type(aid, x["name"])))
        for g in m["aggregates"]:
            agg = {"struct": f"struct {g['name']}", "union": f"union {g['name']}"}.get(g["kind"], g["name"])
            items.append(("agg", g["name"], f"<{hdr}> defines {agg} as a complete type", g["option"],
                          lambda aid, agg=agg: body_complete(aid, agg)))
            for mem in g["members"]:
                opt = mem["option"] if mem["option"] != "BASE" else g["option"]
                items.append(("mem", f"{g['name']}.{mem['name']}",
                              f"{agg} has the member {mem['name']} of type {mem['type']}" + ("[]" if mem["array"] else ""),
                              opt, lambda aid, agg=agg, mem=mem: body_member(aid, agg, mem)))
        for f in m["functions"]:
            f["_hdr"] = hdr
            what = f"<{hdr}> declares {f['name']}()" + (f" as {f['decl']}" if f.get("decl") else "")
            items.append(("fn", f["name"], what, f["option"], lambda aid, f=f: body_function(aid, f)))
        for v in m["variables"]:
            items.append(("var", v["name"], f"<{hdr}> declares {v['decl']}", v["option"],
                          lambda aid, v=v: body_variable(aid, v)))
        if not items:
            continue
        mod = f"{slug(hdr)}.t0"
        d = out / mod
        (d / "t").mkdir(parents=True)
        (d / "MODULE").write_text(f"module  xbd/{mod}\npage    {m['page']}\nvolume  XBD\noption  BASE\n"
                                  f"origin  generated (Tier 0)\nbuildfail FAIL\nlibs    -lpthread -lrt -lm\n")
        asr = [f"# Tier 0: <{hdr}>, generated by gen/tier0.py; not part of the repository.", ""]
        n = 0
        for kind, name, what, opt, mk in items:
            aid = f"T0.{slug(hdr)}.{kind}.{name}"
            body = mk(aid)
            if body is None:
                skipped += 1
                continue
            n += 1
            fname = f"{n:04d}-{kind}-{re.sub(r'[^A-Za-z0-9_]', '_', name)}.c"
            (d / "t" / fname).write_text(PRE.format(what=what, aid=aid, hdr=hdr) + body)
            asr += [f"assertion  {aid}", f"anchor     {m['page']}#DESCRIPTION/{name.split('.')[0]}"]
            asr += ["class      conditional", f"when       {opt}"] if opt != "BASE" else ["class      required"]
            asr += ["since      2024", f"says       {what}", f"test       t/{fname}",
                    "nomutant   generated presence check", ""]
        (d / f"{mod}.asr").write_text("\n".join(asr))
        total += n
    print(f"tier0: {total} checks written under {out} ({skipped} skipped: conditional names or unparsed)")


if __name__ == "__main__":
    main()
