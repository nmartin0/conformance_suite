# Runs on a development machine, never on the system under test. The
# output is committed so the system under test needs only a C compiler.
#
# usage: gen/gen_probe.py [options.list] [probe_options.h]

import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "core/options.list"
dst = Path(sys.argv[2]) if len(sys.argv) > 2 else root / "core/probe_options.h"


def sc_name(macro):
    """_POSIX_X -> _SC_X, _POSIX2_X -> _SC_2_X, _XOPEN_X -> _SC_XOPEN_X."""
    for prefix, repl in (("_POSIX2_", "_SC_2_"), ("_POSIX_", "_SC_"),
                         ("_XOPEN_", "_SC_XOPEN_")):
        if macro.startswith(prefix):
            return repl + macro[len(prefix):]
    raise SystemExit(f"cannot derive sysconf name for {macro}")


rows = []
for n, line in enumerate(src.read_text().splitlines(), 1):
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    parts = line.split()
    if len(parts) != 2 or not parts[0].isalnum() or not parts[0].isupper():
        raise SystemExit(f"{src}:{n}: expected 'CODE MACRO'")
    rows.append((parts[0], parts[1], sc_name(parts[1])))

out = [
    "/*",
    " * probe_options.h - option table for probe.c.",
    " *",
    " * Copyright (c) 2026 Nicholas Martin. All rights reserved.",
    " *",
    " * GENERATED by gen/gen_probe.py from core/options.list. Do not edit.",
    " */",
]
for code, macro, sc in rows:
    out += [
        f'\t{{ "{code}", "{macro}",',
        f"#ifdef {macro}",
        f"\t  1, (long)({macro}),",
        "#else",
        "\t  0, 0,",
        "#endif",
        f"#ifdef {sc}",
        f"\t  1, {sc} }},",
        "#else",
        "\t  0, 0 },",
        "#endif",
    ]
dst.write_text("\n".join(out) + "\n")
print(f"wrote {dst} ({len(rows)} options)")
